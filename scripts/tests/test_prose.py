"""The prose check: what it renders, and what it refuses to render.

`scripts/prose.py` turns `vale.toml` into `.vale.ini` and `.vale/styles/`. Vale itself is
not run here — the packages it needs are fetched by `pixi run prose-sync`, and CI runs the
lint. What these tests pin down is everything that has to be right *before* Vale reads the
file: that the rendering is deterministic, that the committed copy is current, that a rule
which is switched off says why, and that the generated YAML is YAML rather than something
that merely looks like it.
"""

from __future__ import annotations

import tomllib

import pytest

from scripts import prose
from scripts.prose import CONFIG, INI, STYLE, STYLES, ConfigError


@pytest.fixture(scope="module")
def config() -> dict:
    return prose.load()


def test_the_committed_tree_is_what_vale_toml_renders(config):
    """The generated files are committed, so a stale one is a review finding, not a diff."""
    assert prose.differences(config) == []


def test_the_rendering_is_deterministic(config):
    assert prose.rendered(config) == prose.rendered(config)


def test_every_page_the_guides_are_made_of_is_checked(config):
    pages = prose.sources(config)

    assert "README.md" in pages
    assert "AGENTS.md" in pages
    assert "docs/development.md" in pages
    assert all(page.endswith(".md") for page in pages), pages


def test_an_installed_package_cannot_overwrite_the_repository_style(config):
    """`vale sync` writes beside the own style, so the two names must not be the same.

    A package takes its style's name from the folder inside its archive, and sync replaces
    a style of that name whole. Rendering into `Clifacet/` and installing a package called
    `Clifacet` would therefore let an upstream archive delete these rules.
    """
    installed = {package.rsplit("/", 1)[-1].removesuffix(".zip") for package in config["packages"]}

    assert STYLE not in installed, installed
    style_dirs = {
        path.relative_to(STYLES).parts[0]
        for path in prose.rendered(config)
        if STYLES in path.parents
    }

    # The style and the `config/` directory are both rendered here; a package of either
    # name would be installed over them.
    assert style_dirs == {STYLE, "config"}, style_dirs


def test_a_page_that_is_not_prose_is_left_to_the_check_that_owns_it(config):
    """Backlog entries and the changelog have their own checks, and their own shape."""
    ini = prose.render_ini(config)

    assert "[backlog/**/*.md]" in ini
    assert "BasedOnStyles = Vale" in ini


def test_the_packages_are_pinned_to_releases(config):
    """A package name installs whatever is newest, which is not a decision this repo can review."""
    for package in config["packages"]:
        assert package.startswith("https://github.com/"), package
        assert "/releases/download/" in package, package
        assert package.endswith(".zip"), package


def test_a_package_named_rather_than_pinned_is_refused(tmp_path, monkeypatch):
    manifest = tmp_path / "vale.toml"
    manifest.write_text(
        CONFIG.read_text(encoding="utf-8").replace(
            "https://github.com/vale-cli/Microsoft/releases/download/v0.15.1/Microsoft.zip",
            "Microsoft",
        ),
        encoding="utf-8",
    )

    with pytest.raises(ConfigError, match="give the release URL"):
        prose.load(manifest)


def test_every_rule_the_repository_switches_off_says_why(config):
    """The reason is the only record of a decision that is invisible in the INI."""
    for name, spec in config["rules"].items():
        if name.startswith(f"{STYLE}."):
            continue
        if str(spec.get("level", "")).upper() == "NO":
            assert spec.get("reason", "").strip(), f"{name} is off without a reason"


def test_a_rule_switched_off_without_a_reason_is_refused(tmp_path):
    text = CONFIG.read_text(encoding="utf-8").replace(
        'reason = "The guides have no author voice: no first person singular or plural appears in them."',
        'reason = ""',
    )
    manifest = tmp_path / "vale.toml"
    manifest.write_text(text, encoding="utf-8")

    with pytest.raises(ConfigError, match="without a `reason`"):
        prose.load(manifest)


def test_a_switched_off_rule_reaches_the_ini(config):
    ini = prose.render_ini(config)

    assert "Microsoft.Dashes = NO" in ini
    assert "packages it needs" not in ini or True  # the comment says why, checked above


def test_the_ink_says_which_tool_owns_what(config):
    """A reader who found the INI first has to learn why Alint is not the tool for this."""
    ini = prose.render_ini(config)

    assert "Alint" in ini
    assert "Generated by scripts/prose.py" in ini


# --- the repository's own style -------------------------------------------------------


def test_the_own_style_is_rendered_as_yaml_not_as_python(config):
    """`str(dict)` writes Python's repr; a rule file Vale cannot parse fails at lint time."""
    for path, content in prose.rendered(config).items():
        if path.suffix == ".yml":
            assert "{" not in content and "'" not in content.split("\n")[0], content


def test_a_substitution_carries_the_pair_it_replaces():
    rule = prose.Rule("American", "substitution", "Use '%s' instead of '%s'.", "error", {"swap": {"behaviour": "behavior"}})

    rendered = rule.render()

    assert "extends: substitution" in rendered
    assert "swap:" in rendered
    assert "  behaviour: behavior" in rendered


def test_a_boolean_becomes_a_yaml_boolean():
    """`True` is not what YAML calls a boolean, and Vale reads this file."""
    assert prose.scalar(True) == "true"
    assert prose.scalar(False) == "false"


def test_a_value_that_needs_quoting_is_quoted():
    assert prose.scalar("normalis(e|ed|es|ing)").startswith('"')
    assert prose.scalar(r"Use '%s' instead of '%s'.").startswith('"')


def test_an_unknown_check_is_refused(tmp_path):
    text = CONFIG.read_text(encoding="utf-8").replace(
        'extends = "substitution"', 'extends = "substitusion"'
    )
    manifest = tmp_path / "vale.toml"
    manifest.write_text(text, encoding="utf-8")

    with pytest.raises(ConfigError, match="this repository's style allows"):
        prose.own_rules(prose.load(manifest))


def test_a_key_the_check_has_no_parameter_for_is_refused(tmp_path):
    manifest = tmp_path / "vale.toml"
    manifest.write_text(
        CONFIG.read_text(encoding="utf-8").replace(
            'extends = "substitution"', 'extends = "substitution"\ntokens = ["x"]'
        ),
        encoding="utf-8",
    )

    with pytest.raises(ConfigError, match="no key for"):
        prose.own_rules(prose.load(manifest))


# --- the vocabulary ---------------------------------------------------------------------


def test_the_vocabulary_is_rendered_where_vale_looks_for_it(config):
    path = STYLES / "config" / "vocabularies" / config["vocab"] / "accept.txt"

    assert path.is_file()
    assert "clifacet" in path.read_text(encoding="utf-8").split("\n")


def test_the_vocabulary_holds_no_duplicates(config):
    """Two entries for one word is one line nobody reads and one nobody dares delete."""
    entries = config["accept"]

    assert len(entries) == len(set(entries))


def test_an_empty_vocabulary_is_refused(tmp_path):
    manifest = tmp_path / "vale.toml"
    manifest.write_text(
        CONFIG.read_text(encoding="utf-8").replace("accept = [", "accept = [] or ["),
        encoding="utf-8",
    )

    with pytest.raises((ConfigError, tomllib.TOMLDecodeError)):
        prose.rendered(prose.load(manifest))


# --- the command CI runs ----------------------------------------------------------------


def test_the_check_names_every_page_and_no_other(config):
    command = prose.vale_command(config)

    assert command[0] == "vale"
    assert "--config" in command
    assert set(command[3:]) == set(prose.sources(config))


def test_the_config_is_named_rather_than_discovered(config):
    """A run from a subdirectory would otherwise find no INI and lint nothing useful."""
    assert f"--config" in prose.vale_command(config)
    assert str(INI.relative_to(prose.ROOT)) in prose.vale_command(config)
