//! The map of the CLI: the root, its tree, and the request they validate into.
//!
//! One file per leaf, and this file is the only place they are registered — a `mod`
//! line, a [`Verb`] variant and an [`Action`] variant each (decision-15's convention,
//! written by hand). A leaf file holds everything about its command: the `clap` struct,
//! the validated input, its own bridge and questions, and the arguments it forwards.
//!
//! Adding a leaf is a new file plus three lines here and one arm in
//! [`invocation_of`](crate::invocation_of). A missing [`Action`] variant is a compile
//! error, not a forgotten arm: the conversion, the questions and their order are
//! generated by `#[clifacet::subcommands]` (decision-14).

